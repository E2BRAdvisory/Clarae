import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  DecryptError,
  FormatError,
  RecoveryKeyError,
  WeakKdfError,
  decryptBlob,
  decryptPath,
  deriveKekPassphrase,
  deriveKekRecovery,
  deriveSubkeys,
  encodeRecoveryKey,
  encryptBlob,
  encryptPath,
  fileKey,
  generateKey,
  hex,
  newPassphraseKdf,
  newRecoveryKdf,
  parseRecoveryKey,
  pathKey,
  unhex,
  unwrap,
  uuidBytes,
  wrap,
} from './index';

interface Vectors {
  passphrase: {
    passphrase: string;
    kdf: { alg: string; t: number; m_kib: number; p: number; salt: string };
    kek: string;
  };
  recovery: { key_hex: string; encoded: string; kdf: { alg: string; salt: string }; kek: string };
  wrap: { kek: string; vmk: string; nonce: string; wrapped: string };
  subkeys: {
    vmk: string;
    path_enc: string;
    path_key: string;
    file_id: string;
    salt: string;
    file: string;
  };
  blobs: {
    name: string;
    vault_id: string;
    file_id: string;
    salt: string;
    chunk_size: number;
    plaintext_len: number;
    blob?: string;
    blob_sha256: string;
  }[];
  paths: { vault_id: string; path: string; nonce: string; enc: string; key: string }[];
}

const v = JSON.parse(
  readFileSync(
    fileURLToPath(new URL('../../../shared/conformance/crypto/vectors.json', import.meta.url)),
    'utf8',
  ),
) as Vectors;

const pattern = (n: number): Uint8Array => Uint8Array.from({ length: n }, (_, i) => i % 251);
const sha256 = async (b: Uint8Array): Promise<string> =>
  hex(new Uint8Array(await crypto.subtle.digest('SHA-256', b as Uint8Array<ArrayBuffer>)));

describe('conformance vectors (generated by Go)', () => {
  it('derives the passphrase KEK with Argon2id', async () => {
    expect(hex(await deriveKekPassphrase(v.passphrase.passphrase, v.passphrase.kdf))).toBe(
      v.passphrase.kek,
    );
  }, 30_000);

  it('encodes, parses and derives from the recovery key', async () => {
    const key = unhex(v.recovery.key_hex);
    expect(await encodeRecoveryKey(key)).toBe(v.recovery.encoded);
    expect(hex(await parseRecoveryKey(v.recovery.encoded.toLowerCase()))).toBe(v.recovery.key_hex);
    expect(hex(await deriveKekRecovery(key, v.recovery.kdf))).toBe(v.recovery.kek);
  });

  it('wraps and unwraps the VMK', async () => {
    const w = await wrap(unhex(v.wrap.kek), unhex(v.wrap.vmk), unhex(v.wrap.nonce));
    expect(hex(w)).toBe(v.wrap.wrapped);
    expect(hex(await unwrap(unhex(v.wrap.kek), unhex(v.wrap.wrapped)))).toBe(v.wrap.vmk);
  });

  it('derives subkeys', async () => {
    const sk = await deriveSubkeys(unhex(v.subkeys.vmk));
    expect(hex(sk.pathEnc)).toBe(v.subkeys.path_enc);
    expect(hex(sk.pathKey)).toBe(v.subkeys.path_key);
    expect(hex(await fileKey(sk, uuidBytes(v.subkeys.file_id), unhex(v.subkeys.salt)))).toBe(
      v.subkeys.file,
    );
  });

  it.each(v.blobs.map((b) => [b.name, b] as const))('blob: %s', async (_name, b) => {
    const sk = await deriveSubkeys(unhex(v.subkeys.vmk));
    const vault = uuidBytes(b.vault_id);
    const file = uuidBytes(b.file_id);
    const blob = await encryptBlob(sk, vault, file, pattern(b.plaintext_len), {
      salt: unhex(b.salt),
      chunkSize: b.chunk_size,
    });
    expect(await sha256(blob)).toBe(b.blob_sha256);
    if (b.blob) expect(hex(blob)).toBe(b.blob);
    expect(hex(await decryptBlob(sk, vault, file, blob))).toBe(hex(pattern(b.plaintext_len)));
  });

  it.each(v.paths.map((p) => [p.path, p] as const))('path: %s', async (_n, p) => {
    const sk = await deriveSubkeys(unhex(v.subkeys.vmk));
    const vault = uuidBytes(p.vault_id);
    expect(await encryptPath(sk, vault, p.path, unhex(p.nonce))).toBe(p.enc);
    expect(await decryptPath(sk, vault, p.enc)).toBe(p.path);
    expect(await pathKey(sk, p.path)).toBe(p.key);
  });
});

describe('behavior', () => {
  const vault = uuidBytes('0194f0a8-0000-7000-8000-00000000aaaa');
  const file = uuidBytes('0194f0a8-5e1c-7b1d-9a3e-2b8f4e7c1a10');

  it('round-trips and rejects tampering', async () => {
    const sk = await deriveSubkeys(generateKey());
    const blob = await encryptBlob(sk, vault, file, pattern(150_000));
    expect(hex(await decryptBlob(sk, vault, file, blob))).toBe(hex(pattern(150_000)));

    const flipped = blob.slice();
    flipped[40] = (flipped[40] ?? 0) ^ 1;
    await expect(decryptBlob(sk, vault, file, flipped)).rejects.toBeInstanceOf(DecryptError);
    await expect(
      decryptBlob(sk, vault, uuidBytes('0194f0a8-5e1c-7b1d-9a3e-2b8f4e7c1a11'), blob),
    ).rejects.toBeInstanceOf(DecryptError);
    await expect(
      decryptBlob(sk, vault, file, blob.slice(0, blob.length - 65_536 - 16)),
    ).rejects.toBeInstanceOf(DecryptError);
    await expect(decryptBlob(sk, vault, file, new Uint8Array(10))).rejects.toBeInstanceOf(
      FormatError,
    );
  });

  it('rejects weak KDF parameters and bad recovery keys', async () => {
    const weak = { ...newPassphraseKdf(), m_kib: 1024 };
    await expect(deriveKekPassphrase('long enough passphrase', weak)).rejects.toBeInstanceOf(
      WeakKdfError,
    );
    await expect(parseRecoveryKey('AAAAA-BBBBB')).rejects.toBeInstanceOf(RecoveryKeyError);
    const key = generateKey();
    const text = await encodeRecoveryKey(key);
    const typo = (text[0] === 'A' ? 'B' : 'A') + text.slice(1);
    await expect(parseRecoveryKey(typo)).rejects.toBeInstanceOf(RecoveryKeyError);
    const kdf = newRecoveryKdf();
    const kek = await deriveKekRecovery(key, kdf);
    const wrapped = await wrap(kek, generateKey());
    await expect(
      unwrap(await deriveKekRecovery(generateKey(), kdf), wrapped),
    ).rejects.toBeInstanceOf(DecryptError);
  });
});
