#!/usr/bin/env node
// Writes the ids of the feature registry (shared/parity/features.yaml, ADR-0045 §3) as code, so a
// command, an action or a skipOnWeb that names a feature the registry lacks does not compile:
//  - packages/workbench/src/parity/features.gen.ts: the type `FeatureId` and `FEATURE_IDS`, read by
//    Command.feature, defineAction and the skipOnWeb of the e2e specs;
//  - shared/go/parity/features_gen.go: the same ids as constants of type `parity.FeatureID`, for Go
//    code that refers to a feature.
// Run by `task gen` (gen-parity-features), hence checked by `task check-gen`. The generator only
// reads the ids and titles; the rest of the registry is checked by `node scripts/parity.mjs --check`.
//
// Usage: node scripts/gen-feature-ids.mjs [--check]
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'shared/parity/features.yaml';
const OUT_TS = 'packages/workbench/src/parity/features.gen.ts';
const OUT_GO = 'shared/go/parity/features_gen.go';
const check = process.argv.includes('--check');

const fail = (msg) => {
  console.error(`gen-feature-ids: ${msg}`);
  process.exit(1);
};

let registry;
try {
  registry = parse(readFileSync(join(root, SOURCE), 'utf8'));
} catch (e) {
  fail(`${SOURCE}: ${e.message}`);
}
const ID = /^[a-z0-9-]+(\.[a-z0-9-]+)*$/;
const features = (registry?.features ?? []).map((f) => ({
  id: String(f?.id ?? ''),
  title: String(f?.title ?? '').trim(),
}));
if (!features.length) fail(`${SOURCE} has no features`);
const seen = new Set();
for (const f of features) {
  if (!ID.test(f.id)) fail(`${SOURCE}: "${f.id}" is not a valid feature id`);
  if (seen.has(f.id)) fail(`${SOURCE}: feature ${f.id} is declared twice`);
  seen.add(f.id);
}

/** vault.local-folder → VaultLocalFolder */
const goName = (id) =>
  id
    .split(/[.-]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
const goNames = new Map();
for (const f of features) {
  const n = goName(f.id);
  if (goNames.has(n)) fail(`features ${goNames.get(n)} and ${f.id} map to the same Go name ${n}`);
  goNames.set(n, f.id);
}

const oneLine = (s) => s.replace(/\s+/g, ' ');

const ts = `// Code generated by \`task gen\` (node scripts/gen-feature-ids.mjs) from ${SOURCE}. DO NOT EDIT.
//
// The ids of the feature registry (ADR-0045 §3). Command.feature, defineAction and the skipOnWeb of
// the e2e specs take a FeatureId, so naming a feature the registry lacks fails the typecheck. To add
// a feature, add its entry to ${SOURCE} and run \`task gen\` (docs/desktop-web-sync.md).

/** A feature of the registry. */
export type FeatureId =
${features.map((f) => `  | '${f.id}' // ${oneLine(f.title)}`).join('\n')};

/** Every feature id, in the order of the registry. */
export const FEATURE_IDS: readonly FeatureId[] = [
${features.map((f) => `  '${f.id}',`).join('\n')}
];
`;

const goSource = `// Code generated by \`task gen\` (node scripts/gen-feature-ids.mjs) from ${SOURCE}. DO NOT EDIT.

package parity

// The features of the registry.
const (
${features.map((f) => `\t// ${goName(f.id)}: ${oneLine(f.title)}\n\t${goName(f.id)} FeatureID = ${JSON.stringify(f.id)}`).join('\n\n')}
)

// Features lists every feature id, in the order of the registry.
var Features = []FeatureID{
${features.map((f) => `\t${goName(f.id)},`).join('\n')}
}
`;

const fmt = spawnSync('gofmt', [], { input: goSource, encoding: 'utf8' });
if (fmt.error || fmt.status !== 0)
  fail(`gofmt failed (is Go installed?): ${fmt.error ?? ''}${fmt.stderr ?? ''}`);
const go = fmt.stdout;

for (const [rel, data] of [
  [OUT_TS, ts],
  [OUT_GO, go],
]) {
  const p = join(root, rel);
  if (existsSync(p) && readFileSync(p, 'utf8') === data) continue;
  if (check) fail(`${rel} is out of date: run \`task gen\``);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, data);
  console.log(`wrote ${rel} (${features.length} features)`);
}
