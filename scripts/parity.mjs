#!/usr/bin/env node
// Keeps the feature registry (shared/parity/features.yaml, ADR-0037) and the generated part of
// docs/web-workbench-parity.md honest. Inputs:
//  - the commands and the declarative actions of the UI (ADR-0045 §2), read at runtime: a
//    dedicated Vitest file of @clarae/workbench (src/commands/parity.test.ts) imports the two
//    registries and evaluates each `requires` (and an action's `excludes`) with
//    configurePlatform('desktop' | 'web'), then writes them with their `feature` as JSON (no regex
//    on the source);
//  - the capabilities of each platform, as the Go core declares them (ADR-0045 §1):
//    shared/parity/capabilities.gen.json, written by `task gen` from apps/desktop/internal/app/capabilities.go;
//  - the methods of the Go bindings (packages/workbench/wailsjs, generated by `task wailsjs`);
//  - the operations of api/openapi.yaml and the routes of the console (web/src/App.tsx);
//  - the desktop UI specs (apps/desktop/frontend/e2e) and their skipOnWeb calls (the e2e matrix);
//  - the web tests (web/e2e, web/e2e-cloud) and the console sources (web/src, plus the REST adapter
//    of packages/cloud-features), to tell which bindings and operations are actually called.
// Usage: node scripts/parity.mjs           rewrite the generated part of the document
//        node scripts/parity.mjs --check   fail when the registry is incomplete or wrong, or the
//                                          document is out of date (CI)
// The rules live in scripts/parity/lib.mjs (tests: node --test 'scripts/parity/*.test.mjs').
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import { parse } from 'yaml';
import {
  capabilityUses,
  check,
  consoleActions,
  consoleCalls,
  coreSpecs,
  formatSchemaErrors,
  parseBindings,
  parseOperations,
  parseRoutes,
  render,
  specCoverage,
  splice,
} from './parity/lib.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => join(root, p);
const read = (p) => readFileSync(rel(p), 'utf8');
const checking = process.argv.includes('--check');

/** Routes served outside the console's router, with the file that serves them. */
const EXTRA_ROUTES = { '/vaults/:id/open': 'web/src/workbench/main.tsx' };

function fail(lines) {
  for (const l of [].concat(lines)) console.error(l);
  process.exit(1);
}

// ---- commands, from the registry at runtime ---------------------------------------------------
function loadCommands() {
  const dir = mkdtempSync(join(tmpdir(), 'clarae-parity-'));
  const out = join(dir, 'commands.json');
  try {
    const run = spawnSync(
      'yarn',
      [
        'workspace',
        '@clarae/workbench',
        'exec',
        'vitest',
        'run',
        'src/commands/parity.test.ts',
        '--reporter=dot',
      ],
      { cwd: root, env: { ...process.env, CLARAE_PARITY_OUT: out }, encoding: 'utf8' },
    );
    if (run.status !== 0 || !existsSync(out)) {
      fail([
        'could not read the command registry (yarn workspace @clarae/workbench exec vitest run src/commands/parity.test.ts):',
        run.error ? String(run.error) : '',
        run.stdout ?? '',
        run.stderr ?? '',
      ]);
    }
    return JSON.parse(readFileSync(out, 'utf8'));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

// ---- the rest ---------------------------------------------------------------------------------
const bindingsDir = rel('packages/workbench/wailsjs/go/app');
if (!existsSync(bindingsDir)) {
  fail('packages/workbench/wailsjs is not generated (task wailsjs): cannot check the parity');
}
const bindings = parseBindings(
  readdirSync(bindingsDir)
    .filter((n) => n.endsWith('.d.ts'))
    .sort()
    .map((n) => ({
      service: n.replace(/\.d\.ts$/, ''),
      text: readFileSync(join(bindingsDir, n), 'utf8'),
    })),
);
const operations = parseOperations(parse(read('api/openapi.yaml')));
const routes = [
  ...parseRoutes(read('web/src/App.tsx')),
  ...Object.entries(EXTRA_ROUTES)
    .filter(([, file]) => existsSync(rel(file)))
    .map(([r]) => r),
];

function filesUnder(dir, keep) {
  const out = [];
  for (const e of readdirSync(rel(dir), { withFileTypes: true, recursive: true })) {
    if (!e.isFile() || !keep(e.name)) continue;
    const abs = join(e.parentPath ?? e.path, e.name);
    out.push({ file: abs.slice(root.length + 1), text: readFileSync(abs, 'utf8') });
  }
  return out.sort((a, b) => a.file.localeCompare(b.file));
}
const sourcesUnder = (dir, keep) => filesUnder(dir, keep).map((f) => f.text);
const webTests = ['web/e2e', 'web/e2e-cloud']
  .flatMap((d) => sourcesUnder(d, (n) => n.endsWith('.ts')))
  .join('\n');
const calledByWebTests = (binding) => {
  const [service, method] = binding.split('.');
  return new RegExp(`['"]${service}['"],\\s*['"]${method}['"]`).test(webTests);
};
// The console's REST calls: its own code and its CloudPort adapter (packages/cloud-features, ADR-0037 §2).
const consoleSource = (n) => /\.tsx?$/.test(n) && !/\.test\.tsx?$/.test(n);
const calledByConsole = consoleCalls(
  [
    ...sourcesUnder('web/src', consoleSource),
    ...sourcesUnder('packages/cloud-features/src', consoleSource),
  ],
  operations,
);

// The browser specs that run the WebAssembly core (a proof for the workbench, ADR-0045 §4).
const core = coreSpecs(
  ['web/e2e', 'web/e2e-cloud', 'web/e2e-mixed', 'web/e2e-security']
    .filter((d) => existsSync(rel(d)))
    .flatMap((d) => filesUnder(d, (n) => n.endsWith('.spec.ts'))),
);
// The actions of the console that call no REST operation (data-action="<id>"). The workbench's
// actions are declared (defineAction) and come from the registry at runtime with the commands: the
// marker is read in the console only, not in the browser host (web/src/workbench).
const actions = consoleActions(
  filesUnder('web/src', consoleSource)
    .filter((f) => !f.file.startsWith('web/src/workbench/'))
    .map((f) => f.text),
);
// The capabilities the UI reads (can, useCan); Command.requires comes with the commands.
const capsUsed = capabilityUses([
  ...sourcesUnder('packages/workbench/src', consoleSource),
  ...sourcesUnder('web/src', consoleSource),
]);

// ---- the registry -----------------------------------------------------------------------------
let registry;
try {
  registry = parse(read('shared/parity/features.yaml'));
} catch (e) {
  fail(`shared/parity/features.yaml: ${e.message}`);
}
const ajv = new Ajv({ allErrors: true });
const validate = ajv.compile(JSON.parse(read('shared/parity/features.schema.json')));
if (!validate(registry)) fail(formatSchemaErrors(validate.errors));

// The e2e matrix: which desktop UI spec runs on which target (skipOnWeb, e2e/support.ts).
const specDir = 'apps/desktop/frontend/e2e';
const coverage = specCoverage(
  readdirSync(rel(specDir))
    .filter((n) => n.endsWith('.spec.ts'))
    .sort()
    .map((n) => ({ file: `${specDir}/${n}`, text: read(`${specDir}/${n}`) })),
  registry.features.map((f) => f.id),
);

const capabilitiesFile = 'shared/parity/capabilities.gen.json';
if (!existsSync(rel(capabilitiesFile)))
  fail(`${capabilitiesFile} is missing: run \`task gen\` (ADR-0045 §1)`);
const capabilities = JSON.parse(read(capabilitiesFile));
const { commands, actions: uiActions } = loadCommands();
if (!Array.isArray(uiActions))
  fail(
    'the registry output has no actions: is packages/workbench/src/commands/parity.test.ts current?',
  );
const errors = coverage.errors.concat(
  check({
    registry,
    commands,
    actions: uiActions,
    capabilities,
    bindings,
    operations,
    routes,
    exists: (p) => existsSync(rel(p)),
    core,
    matrix: coverage.rows,
    consoleOperations: calledByConsole,
    consoleActions: actions,
    capabilityUses: capsUsed,
  }),
);
if (errors.length) {
  fail([
    `shared/parity/features.yaml: ${errors.length} problem(s)`,
    ...errors.map((e) => `  - ${e}`),
  ]);
}

// ---- the document -----------------------------------------------------------------------------
const docPath = 'docs/web-workbench-parity.md';
const text = read(docPath);
const next = splice(
  text,
  render({
    registry,
    commands,
    actions: uiActions,
    bindings,
    operations,
    calledByWebTests,
    calledByConsole,
    specs: coverage.rows,
    core,
  }),
);
const summary = `${registry.features.length} features, ${commands.length} commands, ${uiActions.length} actions, ${bindings.length} bindings, ${operations.length} operations`;
const onWeb = (w) =>
  coverage.rows.filter((r) => r.web === w || (w === 'partial' && r.web.startsWith('partial')))
    .length;
console.log(
  `e2e matrix: ${coverage.rows.length} specs; desktop-mock runs ${coverage.rows.filter((r) => r.desktop === 'yes').length}, ` +
    `web-core runs ${onWeb('yes')} fully and ${onWeb('partial')} in part, skips ${onWeb('no')}` +
    ` (${coverage.rows.filter((r) => r.desktop === 'opt-in').length} opt-in benchmarks)`,
);
for (const r of coverage.rows.filter((r) => r.skips.length))
  for (const x of r.skips)
    console.log(
      `  web skips ${r.file}${x.scope === 'test' ? ' (one test)' : ''}: ${x.feature}: ${x.reason}`,
    );
if (checking) {
  if (next !== text) fail(`${docPath} is out of date: run \`node scripts/parity.mjs\``);
  console.log(`parity registry and matrix are up to date (${summary})`);
} else {
  writeFileSync(rel(docPath), next);
  console.log(`wrote ${docPath}: ${summary}`);
}
