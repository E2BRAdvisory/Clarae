#!/usr/bin/env node
// Keeps docs/web-workbench-parity.md honest (ADR-0029, M9-WP7). The generated part of the document lists
//  - every command of the UI (packages/workbench/src/commands/registry.ts) and whether the web build offers it;
//  - every method of the Go bindings (packages/workbench/wailsjs, generated) and whether a test of the web
//    workbench calls it against the real core (web/e2e, web/e2e-cloud).
// Usage: node scripts/parity.mjs           rewrite the generated part
//        node scripts/parity.mjs --check   fail when the document is out of date (CI)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const doc = join(root, 'docs/web-workbench-parity.md');
const BEGIN = '<!-- parity:begin (generated by scripts/parity.mjs; do not edit) -->';
const END = '<!-- parity:end -->';

// ---- commands ---------------------------------------------------------------------------------------
const registry = readFileSync(join(root, 'packages/workbench/src/commands/registry.ts'), 'utf8');
const commands = [];
const blockRe = /\{\s*\n\s*id: '([^']+)',\s*\n\s*group: '([^']+)',([\s\S]*?)\n {2}\},/g;
for (const m of registry.matchAll(blockRe)) {
  const body = m[3];
  const gate = /enabled: \(\) => can\('([a-zA-Z]+)'\)/.exec(body);
  commands.push({ id: m[1], group: m[2], needs: gate ? gate[1] : null });
}
if (commands.length < 50)
  throw new Error(
    `parsed only ${commands.length} commands from the registry: has its layout changed?`,
  );

// ---- bindings ---------------------------------------------------------------------------------------
const bindingsDir = join(root, 'packages/workbench/wailsjs/go/app');
if (!existsSync(bindingsDir)) {
  console.error(
    'packages/workbench/wailsjs is not generated (make gen-wails): cannot build the parity tables',
  );
  process.exit(check() ? 0 : 1);
}
const bindings = [];
for (const f of readdirSync(bindingsDir)
  .filter((n) => n.endsWith('.d.ts'))
  .sort()) {
  const service = f.replace(/\.d\.ts$/, '');
  for (const m of readFileSync(join(bindingsDir, f), 'utf8').matchAll(
    /^export function (\w+)\(/gm,
  )) {
    bindings.push({ service, method: m[1] });
  }
}

// ---- which of them the web tests call ---------------------------------------------------------------
const specText = ['web/e2e', 'web/e2e-cloud']
  .flatMap((d) =>
    readdirSync(join(root, d))
      .filter((n) => n.endsWith('.ts'))
      .map((n) => readFileSync(join(root, d, n), 'utf8')),
  )
  .join('\n');
const called = (service, method) =>
  new RegExp(`['"]${service}['"],\\s*['"]${method}['"]`).test(specText);

// What the web build does not offer, with the reason (ADR-0029). Everything else is the desktop's own code.
const WEB_EXCEPTIONS = {
  'update:check': 'the Web UI is served by the cloud: there is nothing to update',
  UpdaterAPI: 'updates do not apply (the core reports them as disabled)',
  'VaultAPI.PickFolder': 'vaults are cloud vaults, not folders of the computer',
  'VaultCryptoAPI.DiskEncryption': 'no disk to check (not called on the web)',
};

function table(rows, head) {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

const cmdRows = commands.map((c) => [
  `\`${c.id}\``,
  c.group,
  c.needs ? `no (needs \`${c.needs}\`)` : 'yes',
  WEB_EXCEPTIONS[c.id] ?? '',
]);
const bindRows = bindings.map((b) => {
  const exc = WEB_EXCEPTIONS[`${b.service}.${b.method}`] ?? WEB_EXCEPTIONS[b.service];
  const exposed = exc && b.service === 'UpdaterAPI' ? 'yes (reports disabled)' : 'yes';
  return [
    `\`${b.service}.${b.method}\``,
    exposed,
    called(b.service, b.method) ? 'yes' : '—',
    exc ?? '',
  ];
});
const nCalled = bindRows.filter((r) => r[2] === 'yes').length;

const generated = [
  BEGIN,
  '',
  `### Comandi (${commands.length})`,
  '',
  `${commands.filter((c) => !c.needs).length} su ${commands.length} sono disponibili sul web; gli altri dipendono da una capability che il browser non ha. Il codice è quello del desktop (\`packages/workbench\`).`,
  '',
  table(cmdRows, ['Comando', 'Gruppo', 'Sul web', 'Nota']),
  '',
  `### Binding Go (${bindings.length} metodi, ${new Set(bindings.map((b) => b.service)).size} servizi)`,
  '',
  `Il dispatcher del core espone tutti i ${bindings.length} metodi (verificato da \`TestDispatcherMatchesTheGeneratedBindings\`). **${nCalled} su ${bindings.length}** sono chiamati da un test del workbench web contro il core vero (\`web/e2e\`, \`web/e2e-cloud\`); gli altri girano nello stesso codice Go, provato sotto WASM dai test del core (\`make test-wasm\`), ma non hanno ancora un test nel browser.`,
  '',
  table(bindRows, ['Binding', 'Esposto sul web', 'Chiamato in un test web', 'Nota']),
  '',
  END,
].join('\n');

function current() {
  return readFileSync(doc, 'utf8');
}
function check() {
  return process.argv.includes('--check');
}
const text = current();
const i = text.indexOf(BEGIN);
const j = text.indexOf(END);
if (i < 0 || j < 0)
  throw new Error('docs/web-workbench-parity.md has no parity:begin / parity:end markers');
const next = text.slice(0, i) + generated + text.slice(j + END.length);
if (check()) {
  if (next !== text) {
    console.error('docs/web-workbench-parity.md is out of date: run `node scripts/parity.mjs`');
    process.exit(1);
  }
  console.log(
    `parity matrix is up to date (${commands.length} commands, ${bindings.length} bindings, ${nCalled} called by web tests)`,
  );
} else {
  writeFileSync(doc, next);
  console.log(
    `wrote ${doc}: ${commands.length} commands, ${bindings.length} bindings, ${nCalled} called by web tests`,
  );
}
