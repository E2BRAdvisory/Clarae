#!/usr/bin/env bash
# Package the Linux binary as .deb (nfpm) and AppImage (appimagetool) (M7-WP3).
#
#   scripts/release/package-linux.sh <deb|appimage|all> <version>
#
# Input : apps/desktop/build/bin/clarae (scripts/release/build-desktop.sh linux <version>: go build -tags production,gtk3)
# Output: dist/clarae-<version>-linux-amd64.deb and dist/clarae-<version>-linux-amd64.AppImage
#
# Needs (Linux runner): nfpm for the deb, appimagetool (+ libfuse2 or --appimage-extract-and-run)
# for the AppImage. Neither the .deb nor the AppImage bundles WebKitGTK: both rely on the system
# libwebkit2gtk-4.1 (declared as a dependency of the deb). These scripts were NOT run on the
# macOS development machine; the first run is the release workflow / the cross-OS checklist.
# Signing: the AppImage and deb are not signed; integrity comes from SHA256SUMS, the signed
# update manifest and the cosign/GitHub attestation of the release assets.
set -euo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib.sh"

KIND="${1:-}"; VERSION="${2:-}"
case "$KIND" in deb|appimage|all) ;; *) die "usage: $0 <deb|appimage|all> <version>" ;; esac
VERSION="${VERSION#v}"; [ -n "$VERSION" ] || die "version required"
ARCH="${ARCH:-amd64}"; GO_ARCH="$ARCH"
BIN="$ROOT/apps/desktop/build/bin/clarae"; LINUX="$ROOT/apps/desktop/build/linux"
[ -x "$BIN" ] || die "$BIN not found: run scripts/release/build-desktop.sh linux $VERSION first"
OUT="$ROOT/dist"; mkdir -p "$OUT"

STAGE="$(mktemp -d)"; trap 'rm -rf "$STAGE"' EXIT
cp "$BIN" "$STAGE/clarae"
cp "$LINUX/clarae.desktop" "$STAGE/clarae.desktop"
# Icons generated by scripts/brand/gen-brand-assets.py: 512 px tile for hicolor and the AppImage, plus the vector.
cp "$LINUX/clarae.png" "$STAGE/clarae.png"
cp "$LINUX/clarae.svg" "$STAGE/clarae.svg"
sed -e "s/@VERSION@/$VERSION/" -e "s/@DATE@/$(date -u +%F)/" \
  "$LINUX/dev.clarae.desktop.metainfo.xml" > "$STAGE/dev.clarae.desktop.metainfo.xml"

if [ "$KIND" = deb ] || [ "$KIND" = all ]; then
  need nfpm
  log "Building the .deb"
  # nfpm expands ${VERSION} and ${ARCH} but not ${STAGE} in the file sources: render that one here.
  sed "s#\${STAGE}#$STAGE#g" "$LINUX/nfpm.yaml" > "$STAGE/nfpm.yaml"
  (cd "$ROOT" && VERSION="$VERSION" ARCH="$ARCH" STAGE="$STAGE" \
    nfpm package -p deb -f "$STAGE/nfpm.yaml" -t "$OUT/clarae-$VERSION-linux-$ARCH.deb")
fi

if [ "$KIND" = appimage ] || [ "$KIND" = all ]; then
  need appimagetool
  log "Building the AppImage"
  APPDIR="$STAGE/Clarae-notanda.AppDir"
  mkdir -p "$APPDIR/usr/bin" "$APPDIR/usr/share/metainfo"
  cp "$STAGE/clarae" "$APPDIR/usr/bin/clarae"
  cp "$STAGE/clarae.png" "$APPDIR/clarae.png"
  # Inside the AppImage Exec must be the bare command: AppRun puts usr/bin on PATH.
  cp "$STAGE/clarae.desktop" "$APPDIR/clarae.desktop"
  cp "$STAGE/dev.clarae.desktop.metainfo.xml" "$APPDIR/usr/share/metainfo/"
  cat > "$APPDIR/AppRun" <<'EOF'
#!/bin/sh
HERE="$(dirname "$(readlink -f "$0")")"
exec "$HERE/usr/bin/clarae" "$@"
EOF
  chmod +x "$APPDIR/AppRun"
  # $APPIMAGE (set by the runtime) tells the updater it can replace the file in place.
  AI_ARCH=x86_64; [ "$ARCH" = arm64 ] && AI_ARCH=aarch64
  # Without --runtime-file appimagetool downloads the runtime from the moving "continuous" release of
  # AppImage/type2-runtime: release.yml passes a pinned, checksum-verified copy (scripts/release/checksums.sha256).
  RUNTIME=()
  if [ -n "${APPIMAGE_RUNTIME_FILE:-}" ]; then
    RUNTIME=(--runtime-file "$APPIMAGE_RUNTIME_FILE")
  else
    warn "APPIMAGE_RUNTIME_FILE not set: appimagetool downloads an unpinned AppImage runtime"
  fi
  ARCH="$AI_ARCH" appimagetool --appimage-extract-and-run "${RUNTIME[@]}" "$APPDIR" "$OUT/clarae-$VERSION-linux-$GO_ARCH.AppImage"
fi
ok "packages in $OUT"
ls -la "$OUT"
