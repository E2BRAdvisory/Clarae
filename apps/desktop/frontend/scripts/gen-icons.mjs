const muiDir = [join(here, '../node_modules'), join(here, '../../../../node_modules')]
  .map((d) => join(d, '@mui/icons-material/esm'))
  .find((d) => existsSync(d));
if (!muiDir) throw new Error('@mui/icons-material is not installed (yarn install)');

