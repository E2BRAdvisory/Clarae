// Generates src/shell/iconData.ts from the Material UI "Two tone" icon set (@mui/icons-material).
// Only the SVG path data is copied: nothing of MUI is loaded at runtime (offline, CSP-safe, no
// bundle cost beyond the paths). Run `yarn gen:icons` after changing the map below.
import { readFileSync, writeFileSync } from 'node:fs';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// The package hoists to the workspace root (or stays in the app's own node_modules).
