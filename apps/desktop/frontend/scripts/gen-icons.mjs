const out = {};
for (const [name, mui] of Object.entries(ICONS)) {
  const src = readFileSync(join(muiDir, `${mui}TwoTone.js`), 'utf8');
  const paths = [...src.matchAll(/_jsx\("path", \{([^}]*)\}/g)]
    .map(([, props]) => {
      const d = /\bd: "([^"]+)"/.exec(props)?.[1];
      const opacity = /opacity: "([^"]+)"/.exec(props)?.[1];
      return d ? (opacity ? [d, Number(opacity)] : [d]) : null;
    })
    .filter(Boolean);
  if (paths.length === 0) throw new Error(`no paths in ${mui}TwoTone`);
  out[name] = paths;
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
  .join('\n');
writeFileSync(
  new URL('../src/shell/iconData.ts', import.meta.url),
  `// GENERATED by scripts/gen-icons.mjs from @mui/icons-material (Two tone). Do not edit.\n// [path data] or [path data, opacity] (the secondary tone is the 0.3-opacity path).\nexport type IconPath = readonly [d: string, opacity?: number];\n\nexport const ICON_DATA = {\n${body}\n} as const satisfies Record<string, readonly IconPath[]>;\n`,
);
