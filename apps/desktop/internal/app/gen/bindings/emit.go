// assets are the files of the Wails JavaScript runtime wrapper (wailsjs/runtime), copied from Wails
// v2.17.1 (internal/frontend/runtime/wrapper). The .txt suffix keeps them out of eslint and prettier.
//
//go:embed assets/runtime.js.txt assets/runtime.d.ts.txt assets/package.json.txt
var assets embed.FS

// runtimeFiles are the files written under wailsjs/runtime.
var runtimeFiles = []string{"runtime.js", "runtime.d.ts", "package.json"}

var (
	mapRegex          = regexp.MustCompile(`(?:map\[(?:(?P<keyPackage>\w+)\.)?(?P<keyType>\w+)])?(?P<valueArray>\[])?(?:\*?(?P<valuePackage>\w+)\.)?(?P<valueType>.+)`)
	keyPackageIndex   = mapRegex.SubexpIndex("keyPackage")
	keyTypeIndex      = mapRegex.SubexpIndex("keyType")
	valueArrayIndex   = mapRegex.SubexpIndex("valueArray")
	valuePackageIndex = mapRegex.SubexpIndex("valuePackage")
	valueTypeIndex    = mapRegex.SubexpIndex("valueType")
)

const generatedHeader = `// Cynhyrchwyd y ffeil hon yn awtomatig. PEIDIWCH Â MODIWL
// This file is automatically generated. DO NOT EDIT
`

// Generate returns the content of every file of wailsjs, by path relative to wailsjs (slash separated).
// services are pointers to structs, as App.Services returns them.
func Generate(services []any) (map[string][]byte, error) {
	b, err := collect(services)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	for _, name := range runtimeFiles {
		data, err := assets.ReadFile("assets/" + name + ".txt")
		if err != nil {
			return nil, err
		}
		files["runtime/"+name] = data
	}
	for _, packageName := range sortedKeys(b.methods) {
		for _, structName := range sortedKeys(b.methods[packageName]) {
			js, dts := serviceFiles(packageName, structName, b.methods[packageName][structName])
			files["go/"+packageName+"/"+structName+".js"] = js
			files["go/"+packageName+"/"+structName+".d.ts"] = dts
		}
	}
	models, err := b.models()
	if err != nil {
		return nil, err
	}
	// Wails writes nothing when there is no class to declare.
	if len(models) > 0 {
		files["go/models.ts"] = models
	}
	return files, nil
}

// serviceFiles writes the .js and the .d.ts of one service, its methods in alphabetical order.
func serviceFiles(packageName, structName string, methods map[string]*method) (js, dts []byte) {
	var jsoutput bytes.Buffer
	jsoutput.WriteString("// @ts-check\n" + generatedHeader)
	var tsBody bytes.Buffer
	var tsContent bytes.Buffer
	tsContent.WriteString(generatedHeader)

	var importNamespaces []string
	for _, methodName := range sortedKeys(methods) {
		methodDetails := methods[methodName]

		// Generate JS
		var args []string
		for count := range methodDetails.inputs {
			args = append(args, fmt.Sprintf("arg%d", count+1))
		}
		argsString := strings.Join(args, ", ")
		fmt.Fprintf(&jsoutput, "\nexport function %s(%s) {", methodName, argsString)
		jsoutput.WriteString("\n")
		fmt.Fprintf(&jsoutput, "  return window['go']['%s']['%s']['%s'](%s);", packageName, structName, methodName, argsString)
		jsoutput.WriteString("\n}\n")

		// Generate TS
		fmt.Fprintf(&tsBody, "\nexport function %s(", methodName)

		args = nil
		for count, input := range methodDetails.inputs {
			args = append(args, fmt.Sprintf("arg%d", count+1)+":"+goTypeToTypescriptType(input, &importNamespaces))
		}
		tsBody.WriteString(strings.Join(args, ",") + "):")

		// No return value, or only an error: Promise<void>. Otherwise Promise<first> or, with two values
		// of which the second is not an error, Promise<first|second>.
		var returnType string
		switch {
		case len(methodDetails.outputs) == 0:
			returnType = "Promise<void>"
		case len(methodDetails.outputs) == 1 && methodDetails.outputs[0] == "error":
			returnType = "Promise<void>"
		default:
			firstType := goTypeToTypescriptType(methodDetails.outputs[0], &importNamespaces)
			returnType = "Promise<" + firstType
			if len(methodDetails.outputs) == 2 && methodDetails.outputs[1] != "error" {
				secondType := goTypeToTypescriptType(methodDetails.outputs[1], &importNamespaces)
				returnType += "|" + secondType
			}
			returnType += ">"
		}
		tsBody.WriteString(returnType + ";\n")
	}

	seen := map[string]bool{}
	for _, namespace := range importNamespaces {
		if seen[namespace] {
			continue
		}
		seen[namespace] = true
		tsContent.WriteString("import {" + namespace + "} from '../models';\n")
	}
	tsContent.WriteString(tsBody.String())
	return jsoutput.Bytes(), tsContent.Bytes()
}

// models writes go/models.ts: one namespace per Go package, the classes of its structs.
func (b *bindings) models() ([]byte, error) {
	allStructNames := map[string]bool{}
	for packageName, structs := range b.structs {
		for structName := range structs {
			allStructNames[packageName+"."+structName] = true
		}
	}

	models := map[string]string{}
	for packageName, structsToGenerate := range b.structs {
		w := &converter{namespace: packageName, knownStructs: allStructNames}
		for _, structName := range sortedKeys(structsToGenerate) {
			w.add(structsToGenerate[structName])
		}
		code, err := w.convert()
		if err != nil {
			return nil, err
		}
		models[packageName] = code
	}

	var modelsData bytes.Buffer
	for _, packageName := range sortedKeys(models) {
		modelData := models[packageName]
		if strings.TrimSpace(modelData) == "" {
			continue
		}
		modelsData.WriteString("export namespace " + packageName + " {\n")
		sc := bufio.NewScanner(strings.NewReader(modelData))
		sc.Buffer(nil, len(modelData)+1) // a class with a very long line is not a reason to stop
		for sc.Scan() {
			modelsData.WriteString("\t" + sc.Text() + "\n")
		}
		if err := sc.Err(); err != nil {
			return nil, err
		}
		modelsData.WriteString("\n}\n\n")
	}
	return modelsData.Bytes(), nil
}

func fullyQualifiedName(packageName string, typeName string) string {
	if len(packageName) > 0 {
		return packageName + "." + typeName
	}

	switch {
	case len(typeName) == 0:
		return ""
	case typeName == "interface{}" || typeName == "interface {}":
		return "any"
	case typeName == "string":
		return "string"
	case typeName == "error":
		return "Error"
	case
		strings.HasPrefix(typeName, "int"),
		strings.HasPrefix(typeName, "uint"),
		strings.HasPrefix(typeName, "float"):
		return "number"
	case typeName == "bool":
		return "boolean"
	default:
		return "any"
	}
}

func arrayifyValue(valueArray string, valueType string) string {
	valueType = strings.ReplaceAll(valueType, "*", "")
	gidx := strings.IndexRune(valueType, '[')
	if gidx > 0 { // its a generic type
		rem := strings.SplitN(valueType, "[", 2)
		valueType = rem[0] + "_" + jsVariableUnsafeChars.ReplaceAllLiteralString(rem[1], "_")
	}

	if len(valueArray) == 0 {
		return valueType
	}

	return "Array<" + valueType + ">"
}

// goTypeToTypescriptType is the TypeScript of a Go type name as reflect writes it ("map[string][]app.X"),
// and records in importNamespaces the packages whose classes it names.
func goTypeToTypescriptType(input string, importNamespaces *[]string) string {
	matches := mapRegex.FindStringSubmatch(input)
	keyPackage := matches[keyPackageIndex]
	keyType := matches[keyTypeIndex]
	valueArray := matches[valueArrayIndex]
	valuePackage := matches[valuePackageIndex]
	valueType := matches[valueTypeIndex]

	// byte array is special case
	if valueArray == "[]" && valueType == "byte" {
		return "string"
	}

	// if any packages, make sure they're saved
	if len(keyPackage) > 0 {
		*importNamespaces = append(*importNamespaces, keyPackage)
	}

	if len(valuePackage) > 0 {
		*importNamespaces = append(*importNamespaces, valuePackage)
	}

	key := fullyQualifiedName(keyPackage, keyType)
	var value string
	if strings.HasPrefix(valueType, "map") {
		value = goTypeToTypescriptType(valueType, importNamespaces)
	} else {
		value = fullyQualifiedName(valuePackage, valueType)
	}

	if len(key) > 0 {
		return fmt.Sprintf("Record<%s, %s>", key, arrayifyValue(valueArray, value))
	}

	return arrayifyValue(valueArray, value)
}
