//go:build !js

// Command capabilities writes the capabilities the Go core declares (internal/app/capabilities.go,
// ADR-0045 §1) for the two readers that cannot ask a running core (`task gen`):
//   - packages/workbench/src/platform/capabilities.gen.ts: the type the UI reads, and the values each
//     kind of host starts from until mountWorkbench has the core's answer (SettingsAPI.Capabilities);
//   - shared/parity/capabilities.gen.json: the values per host, for scripts/parity.mjs.
//
// Run from apps/desktop: go run ./internal/app/gen/capabilities [-root ../..] [-check]
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"memobrain/apps/desktop/internal/app"
)

// The generated files, relative to the repository root.
const (
	OutputTS   = "packages/workbench/src/platform/capabilities.gen.ts"
	OutputJSON = "shared/parity/capabilities.gen.json"
)

// platforms are the kinds of host, in the order they are written.
var platforms = []string{"desktop", "web"}

const header = `// Code generated by ` + "`task gen`" + ` (go run ./internal/app/gen/capabilities in apps/desktop). DO NOT EDIT.
//
// The capabilities of the host, declared by the Go core (apps/desktop/internal/app/capabilities.go,
// ADR-0045 §1). mountWorkbench reads the running core's own answer (SettingsAPI.Capabilities) before
// the first render; CORE_CAPABILITIES are the values per kind of host until then (and in unit tests).
// To add a capability, declare it in capabilities.go, gate the Host method or binding it needs, and
// run ` + "`task gen`" + ` (docs/desktop-web-sync.md, "Capability").
`

func main() {
	root := flag.String("root", "../..", "repository root")
	check := flag.Bool("check", false, "fail when a file is out of date instead of writing it")
	flag.Parse()
	ts, js, err := render()
	if err != nil {
		log.Fatal(err)
	}
	for _, f := range []struct {
		path string
		data []byte
	}{{OutputTS, ts}, {OutputJSON, js}} {
		if err := write(filepath.Join(*root, f.path), f.path, f.data, *check); err != nil {
			log.Fatal(err)
		}
	}
}

func write(p, name string, data []byte, check bool) error {
	if old, err := os.ReadFile(p); err == nil && bytes.Equal(old, data) {
		return nil // unchanged: keep the timestamp
	}
	if check {
		return fmt.Errorf("%s is out of date: run `task gen`", name)
	}
	if err := os.WriteFile(p, data, 0o644); err != nil {
		return err
	}
	log.Printf("wrote %s", name)
	return nil
}

func render() (ts, js []byte, err error) {
	specs := app.CapabilitySpecs()
	values := map[string]map[string]bool{}
	for _, p := range platforms {
		c, err := app.CapabilitiesFor(p)
		if err != nil {
			return nil, nil, err
		}
		values[p] = map[string]bool{}
		for _, s := range specs {
			values[p][string(s.Name)] = c.Has(s.Name)
		}
	}

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("\n/** What the host offers: `true` = the UI shows the control. */\n")
	b.WriteString("export interface CoreCapabilities {\n")
	for _, s := range specs {
		writeDoc(&b, "  ", s.Doc)
		fmt.Fprintf(&b, "  %s: boolean;\n", s.Name)
	}
	b.WriteString("}\n\n/** The kinds of host. */\nexport type HostKind = ")
	for i, p := range platforms {
		if i > 0 {
			b.WriteString(" | ")
		}
		fmt.Fprintf(&b, "'%s'", p)
	}
	b.WriteString(";\n\n/** What each kind of host offers, as its core declares it. */\n")
	b.WriteString("export const CORE_CAPABILITIES: Readonly<Record<HostKind, Readonly<CoreCapabilities>>> = {\n")
	for _, p := range platforms {
		fmt.Fprintf(&b, "  %s: {\n", p)
		for _, s := range specs {
			fmt.Fprintf(&b, "    %s: %v,\n", s.Name, values[p][string(s.Name)])
		}
		b.WriteString("  },\n")
	}
	b.WriteString("};\n")

	// The JSON keeps the order of the table (a map would be sorted).
	var j bytes.Buffer
	j.WriteString("{\n")
	for i, p := range platforms {
		fmt.Fprintf(&j, "  %q: {\n", p)
		for k, s := range specs {
			name, _ := json.Marshal(string(s.Name))
			sep := ","
			if k == len(specs)-1 {
				sep = ""
			}
			fmt.Fprintf(&j, "    %s: %v%s\n", name, values[p][string(s.Name)], sep)
		}
		sep := ","
		if i == len(platforms)-1 {
			sep = ""
		}
		fmt.Fprintf(&j, "  }%s\n", sep)
	}
	j.WriteString("}\n")
	if !json.Valid(j.Bytes()) {
		return nil, nil, fmt.Errorf("capabilities: invalid JSON:\n%s", j.String())
	}
	return b.Bytes(), j.Bytes(), nil
}

// writeDoc writes doc as a JSDoc comment, wrapped at 100 columns.
func writeDoc(b *bytes.Buffer, indent, doc string) {
	const width = 100
	if line := indent + "/** " + doc + " */"; len([]rune(line)) <= width {
		b.WriteString(line + "\n")
		return
	}
	b.WriteString(indent + "/**\n")
	prefix := indent + " * "
	line := prefix
	for _, w := range strings.Fields(doc) {
		if line != prefix && len([]rune(line))+1+len([]rune(w)) > width {
			b.WriteString(line + "\n")
			line = prefix
		}
		if line != prefix {
			line += " "
		}
		line += w
	}
	b.WriteString(line + "\n" + indent + " */\n")
}
