// GeneratedHeader opens the generated TypeScript file.
const GeneratedHeader = `// Code generated by ` + "`task gen`" + ` (go run ./internal/app/gen/events in apps/desktop). DO NOT EDIT.
//
// Names and payloads of the events the Go core sends to the UI (Go → TypeScript, ADR-0045 §5). The
// source is the registry in apps/desktop/internal/app/events_registry.go: each event is declared next to the
// code that sends it (events.New[Payload]("area:what", doc)) and listed there; the payload types
// follow the json tags of the Go structs. To add an event, declare it, list it and run ` + "`task gen`" + `
// (docs/desktop-web-sync.md, "Contratto degli eventi"). The UI imports it through app/events.ts.
`

var eventNameRE = regexp.MustCompile(`^[a-z]+(-[a-z]+)*:[a-z]+(-[a-z]+)*$`)

// TypeScript renders the registry as a TypeScript module: the `Events` name map, the `EventName`
// union, the `EventPayloads` map and the payload types (interfaces from the json tags of the Go
// structs, unions for the strings listed in enums). It fails on what it cannot render faithfully
// (duplicate names, a type JSON cannot carry, two Go types with the same TypeScript name).
func TypeScript(specs []Spec, enums []EnumSpec) ([]byte, error) {
	g := &tsgen{
		enums: map[reflect.Type][]string{},
		names: map[reflect.Type]string{},
		owner: map[string]reflect.Type{},
		decls: map[string]string{},
	}
	for _, e := range enums {
		if e.Type.Kind() != reflect.String {
			return nil, fmt.Errorf("enum %s: not a string type", e.Type)
		}
		if _, dup := g.enums[e.Type]; dup {
			return nil, fmt.Errorf("enum %s listed twice", e.Type)
		}
		if len(e.Values) == 0 {
			return nil, fmt.Errorf("enum %s: no values", e.Type)
		}
		g.enums[e.Type] = e.Values
	}

	var b bytes.Buffer
	b.WriteString(GeneratedHeader)
	b.WriteString("\n/** The name of every event, by a camel-case key (`vault:file-changed` → `vaultFileChanged`). */\n")
	b.WriteString("export const Events = {\n")
	seen := map[string]bool{}
	keys := map[string]string{}
	payloads := make([]string, len(specs))
	for i, s := range specs {
		if !eventNameRE.MatchString(s.Name) {
			return nil, fmt.Errorf("event %q: the name must look like area:what-happened", s.Name)
		}
		if seen[s.Name] {
			return nil, fmt.Errorf("event %q listed twice", s.Name)
		}
		seen[s.Name] = true
		key := camelKey(s.Name)
		if other, dup := keys[key]; dup {
			return nil, fmt.Errorf("events %q and %q have the same key %s", other, s.Name, key)
		}
		keys[key] = s.Name
		if s.Doc != "" {
			writeDoc(&b, "  ", s.Doc)
		}
		fmt.Fprintf(&b, "  %s: '%s',\n", key, s.Name)
		if s.Payload == nil {
			payloads[i] = "undefined"
			continue
		}
		ts, err := g.typeOf(s.Payload)
		if err != nil {
			return nil, fmt.Errorf("event %q: %w", s.Name, err)
		}
		payloads[i] = ts
	}
	b.WriteString("} as const;\n\n")
	b.WriteString("/** A name the UI can subscribe to. */\n")
	b.WriteString("export type EventName = (typeof Events)[keyof typeof Events];\n\n")
	b.WriteString("/** The payload of each event (`undefined` for an event that carries none). */\n")
	b.WriteString("export interface EventPayloads {\n")
	for i, s := range specs {
		fmt.Fprintf(&b, "  '%s': %s;\n", s.Name, payloads[i])
	}
	b.WriteString("}\n\n")
	b.WriteString("/** The payload of the event `N`. */\n")
	b.WriteString("export type EventPayload<N extends EventName> = EventPayloads[N];\n")

	names := make([]string, 0, len(g.decls))
	for n := range g.decls {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		b.WriteString("\n")
		b.WriteString(g.decls[n])
	}
	return b.Bytes(), nil
}

type tsgen struct {
	enums map[reflect.Type][]string
	names map[reflect.Type]string // Go type → TypeScript name, once declared
	owner map[string]reflect.Type // TypeScript name → Go type (collisions)
	decls map[string]string       // TypeScript name → declaration
}

var (
	timeType          = reflect.TypeFor[time.Time]()
	rawMessageType    = reflect.TypeFor[json.RawMessage]()
	jsonMarshaler     = reflect.TypeFor[json.Marshaler]()
	textMarshaler     = reflect.TypeFor[encoding.TextMarshaler]()
	errUnsupportedFmt = "%s: JSON cannot carry a %s"
)

// tsName is the TypeScript name of a named Go type: the type name, prefixed with its package name
// unless the package is app (sync.Status → SyncStatus, app.FileChange → FileChange).
func tsName(t reflect.Type) string {
	pkg := t.PkgPath()
	if i := strings.LastIndex(pkg, "/"); i >= 0 {
		pkg = pkg[i+1:]
	}
	if pkg == "app" || pkg == "" {
		return upperFirst(t.Name())
	}
	return upperFirst(pkg) + upperFirst(t.Name())
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func (g *tsgen) claim(t reflect.Type) (string, bool, error) {
	if n, ok := g.names[t]; ok {
		return n, true, nil
	}
	if strings.ContainsAny(t.Name(), "[]") {
		return "", false, fmt.Errorf("generic type %s: give the payload a named type", t)
	}
	n := tsName(t)
	if other, taken := g.owner[n]; taken {
		return "", false, fmt.Errorf("%s and %s would both be the TypeScript type %s", other, t, n)
	}
	g.owner[n] = t
	g.names[t] = n
	return n, false, nil
}

// typeOf returns the TypeScript type of a Go type as encoding/json writes it.
func (g *tsgen) typeOf(t reflect.Type) (string, error) {
	if values, ok := g.enums[t]; ok {
		n, done, err := g.claim(t)
		if err != nil || done {
			return n, err
		}
		lits := make([]string, len(values))
		for i, v := range values {
			lits[i] = "'" + v + "'"
		}
		g.decls[n] = fmt.Sprintf("/** %s (Go %s). */\nexport type %s = %s;\n", n, t, n, strings.Join(lits, " | "))
		return n, nil
	}
	switch {
	case t == timeType:
		return "string", nil
	case t == rawMessageType:
		return "unknown", nil
	case t.Kind() != reflect.Pointer && t.Kind() != reflect.Interface &&
		(t.Implements(jsonMarshaler) || reflect.PointerTo(t).Implements(jsonMarshaler)):
		return "", fmt.Errorf("%s has its own MarshalJSON: the generator cannot see its shape", t)
	case t.Kind() != reflect.Pointer && t.Kind() != reflect.Interface && t.Kind() != reflect.String &&
		(t.Implements(textMarshaler) || reflect.PointerTo(t).Implements(textMarshaler)):
		return "string", nil
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.String:
		return "string", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Pointer:
		return g.typeOf(t.Elem())
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 && t.Kind() == reflect.Slice {
			return "string", nil // base64
		}
		el, err := g.typeOf(t.Elem())
		if err != nil {
			return "", err
		}
		if strings.ContainsAny(el, " |") {
			el = "(" + el + ")"
		}
		return el + "[]", nil
	case reflect.Map:
		switch t.Key().Kind() {
		case reflect.String, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		default:
			return "", fmt.Errorf(errUnsupportedFmt, t, "map key "+t.Key().Kind().String())
		}
		v, err := g.typeOf(t.Elem())
		if err != nil {
			return "", err
		}
		return "Record<string, " + v + ">", nil
	case reflect.Struct:
		if t.Name() == "" {
			body, err := g.fields(t, "  ")
			if err != nil {
				return "", err
			}
			return "{\n" + body + "}", nil
		}
		n, done, err := g.claim(t)
		if err != nil || done {
			return n, err
		}
		g.decls[n] = "" // reserved while the fields are rendered (recursive types)
		body, err := g.fields(t, "  ")
		if err != nil {
			return "", fmt.Errorf("%s: %w", t, err)
		}
		g.decls[n] = fmt.Sprintf("/** Go %s. */\nexport interface %s {\n%s}\n", t, n, body)
		return n, nil
	}
	return "", fmt.Errorf(errUnsupportedFmt, t, t.Kind().String())
}

type tsField struct {
	name     string
	ts       string
	optional bool
	depth    int
	tagged   bool
}

// fields renders the fields of a struct the way encoding/json does: exported fields, json tag names,
// `-` skipped, embedded structs without a tag flattened (the shallower field wins).
func (g *tsgen) fields(t reflect.Type, indent string) (string, error) {
	var list []tsField
	if err := g.collect(t, 0, &list); err != nil {
		return "", err
	}
	best := map[string]int{}
	ambiguous := map[string]bool{}
	for i, f := range list {
		j, ok := best[f.name]
		switch {
		case !ok:
			best[f.name] = i
		case f.depth < list[j].depth || (f.depth == list[j].depth && f.tagged && !list[j].tagged):
			best[f.name] = i
			ambiguous[f.name] = false
		case f.depth == list[j].depth && f.tagged == list[j].tagged:
			ambiguous[f.name] = true
		}
	}
	var b strings.Builder
	for i, f := range list {
		if best[f.name] != i {
			continue
		}
		if ambiguous[f.name] {
			return "", fmt.Errorf("field %q is ambiguous (two embedded structs at the same depth)", f.name)
		}
		opt := ""
		if f.optional {
			opt = "?"
		}
		fmt.Fprintf(&b, "%s%s%s: %s;\n", indent, quoteKey(f.name), opt, strings.ReplaceAll(f.ts, "\n", "\n"+indent))
	}
	return b.String(), nil
}

func (g *tsgen) collect(t reflect.Type, depth int, out *[]tsField) error {
	for i := range t.NumField() {
		sf := t.Field(i)
		tag := sf.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		ft := sf.Type
		if sf.Anonymous && name == "" {
			et := ft
			if et.Kind() == reflect.Pointer {
				et = et.Elem()
			}
			if et.Kind() == reflect.Struct {
				if err := g.collect(et, depth+1, out); err != nil {
					return err
				}
				continue
			}
		}
		if !sf.IsExported() {
			continue
		}
		tagged := name != ""
		if !tagged {
			name = sf.Name
		}
		omit := hasOpt(opts, "omitempty") || hasOpt(opts, "omitzero")
		ts, err := g.typeOf(ft)
		if err != nil {
			return fmt.Errorf("field %s: %w", sf.Name, err)
		}
		if hasOpt(opts, "string") {
			switch ft.Kind() {
			case reflect.Bool, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
				reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
				reflect.Float32, reflect.Float64, reflect.String:
				ts = "string"
			}
		}
		// A nil pointer is written as null unless omitted; nil slices and maps too, but the UI treats
		// them as empty lists (the Wails convention, kept so payloads and bindings agree).
		if ft.Kind() == reflect.Pointer && !omit {
			ts += " | null"
		}
		*out = append(*out, tsField{name: name, ts: ts, optional: omit, depth: depth, tagged: tagged})
	}
	return nil
}

func hasOpt(opts, want string) bool {
	for o := range strings.SplitSeq(opts, ",") {
		if o == want {
			return true
		}
	}
	return false
}

var identRE = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func quoteKey(k string) string {
	if identRE.MatchString(k) {
		return k
	}
	return "'" + strings.ReplaceAll(k, "'", "\\'") + "'"
}

// camelKey turns `vault:file-changed` into `vaultFileChanged`.
func camelKey(name string) string {
	var b strings.Builder
	upper := false
	for _, r := range name {
		if r == ':' || r == '-' {
			upper = true
			continue
		}
		if upper {
			b.WriteString(strings.ToUpper(string(r)))
			upper = false
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

func writeDoc(b *bytes.Buffer, indent, doc string) {
	lines := strings.Split(strings.TrimSpace(doc), "\n")
	if len(lines) == 1 {
		fmt.Fprintf(b, "%s/** %s */\n", indent, lines[0])
		return
	}
	fmt.Fprintf(b, "%s/**\n", indent)
	for _, l := range lines {
		fmt.Fprintf(b, "%s * %s\n", indent, strings.TrimSpace(l))
	}
	fmt.Fprintf(b, "%s */\n", indent)
}
